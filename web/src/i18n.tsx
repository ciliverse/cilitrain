type Key = keyof (typeof dict)['zh']

type I18nCtx = {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: Key) => string
  statusLabel: (status: string) => string
}

const Ctx = createContext<I18nCtx | null>(null)

function detectLang(): Lang {
  const saved = localStorage.getItem('cilitrain_lang')
  if (saved === 'zh' || saved === 'en') return saved
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'zh'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang)
  const setLang = useCallback((l: Lang) => {
    localStorage.setItem('cilitrain_lang', l)
    setLangState(l)
  }, [])
  const t = useCallback((key: Key) => dict[lang][key] || dict.en[key] || key, [lang])
  const statusLabel = useCallback(
    (status: string) => {
      const k = `status_${status}` as Key
      return dict[lang][k] || status
    },
    [lang],
  )
  const value = useMemo(() => ({ lang, setLang, t, statusLabel }), [lang, setLang, t, statusLabel])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const v = useContext(Ctx)
  if (!v) throw new Error('I18nProvider missing')
  return v
}

export function formatDuration(sec?: number | null) {
  if (sec == null) return '—'
  if (sec < 60) return `${sec}s`
  const m = Math.floor(sec / 60)
  const s = sec % 60
  if (m < 60) return `${m}m ${s}s`
  const h = Math.floor(m / 60)
  return `${h}h ${m % 60}m`
}

/** Parse API datetime: treat naive ISO as UTC (legacy responses without Z). */
export function parseApiDate(value: string | number | Date): Date {
  if (value instanceof Date) return value
  if (typeof value === 'number') return new Date(value * (value < 1e12 ? 1000 : 1))
  const s = String(value).trim()
  // "2026-08-03T15:11:08.597423" → UTC
  if (/^\d{4}-\d{2}-\d{2}T[\d:.]+$/.test(s)) {
    return new Date(s + 'Z')
  }
  return new Date(s)
}

/** Display API UTC time in the browser's local timezone. */
export function formatLocalDateTime(
  value?: string | number | Date | null,
  lang: Lang = 'zh',
): string {
  if (value == null || value === '') return '—'
  const d = parseApiDate(value)
  if (Number.isNaN(d.getTime())) return '—'
  return d.toLocaleString(lang === 'en' ? 'en-US' : 'zh-CN', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  })
}

const API_MSG_KEYS: Record<string, Key> = {
  'cancelled by user': 'errCancelledByUser',
  'job not found in cluster': 'errJobNotFound',
  'empty steps': 'errEmptySteps',
  'missing step run': 'errMissingStepRun',
  'pod failed': 'errPodFailed',
  'Job created; waiting for Pod': 'msgJobCreated',
}

export function formatApiMessage(
  msg: string | null | undefined,
  t: (key: Key) => string,
): string {
  if (!msg) return ''
  const key = API_MSG_KEYS[msg]
  if (key) return t(key)
  const lower = msg.toLowerCase()
  if (lower.includes('concurrency limit')) return t('errConcurrency')
  if (lower.includes('queue is full')) return t('errQueueFull')
  if (lower.includes('running services per user')) return t('errServiceCap')
  if (lower.includes('per-user quota')) {
    const cap = /per-user quota \(([^)]+)\)/.exec(msg)?.[1]
    return cap ? `${t('errUserQuota')} (${cap})` : t('errUserQuota')
  }
  if (
    lower.includes('errimagepull') ||
    lower.includes('imagepullbackoff') ||
    lower.includes('back-off pulling') ||
    lower.includes('failed to pull')
  ) {
    return t('errImagePull')
  }
  if (lower.includes('no allocatable nvidia.com/gpu')) return t('errNoGpu')
  return msg
}
